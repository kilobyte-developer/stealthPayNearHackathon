import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Exports the ABIs the frontend needs into src/config/abi/.
 *
 * Only ABIs cross the boundary — never bytecode, never deployment keys. The
 * Next.js app has no reason to compile or deploy contracts.
 */
const OUT_DIR = join(__dirname, "..", "..", "src", "config", "abi");

const TARGETS = [
  { file: "ERC5564Announcer.sol", name: "ERC5564Announcer" },
  { file: "StealthPaymentRouter.sol", name: "StealthPaymentRouter" },
];

function main() {
  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

  for (const { file, name } of TARGETS) {
    const artifactPath = join(
      __dirname,
      "..",
      "artifacts",
      "contracts",
      file,
      `${name}.json`,
    );
    if (!existsSync(artifactPath)) {
      throw new Error(`Artifact missing: ${artifactPath}. Run \`npm run compile\` first.`);
    }

    const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as {
      abi: unknown[];
    };

    const banner =
      `// Generated by contracts/scripts/export-abi.ts — do not edit by hand.\n` +
      `// Source: contracts/contracts/${file}\n\n`;

    const contents =
      `${banner}export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

    writeFileSync(join(OUT_DIR, `${name}.ts`), contents, "utf8");
    console.log(`Exported ${name} ABI (${artifact.abi.length} entries)`);
  }

  writeFileSync(
    join(OUT_DIR, "index.ts"),
    `${TARGETS.map((t) => `export { ${t.name}Abi } from "./${t.name}";`).join("\n")}\n`,
    "utf8",
  );
  console.log(`Wrote ${OUT_DIR}`);
}

main();
